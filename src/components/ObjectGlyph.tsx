interface ObjectGlyphProps {
  icon: ObjectIconId;
  className?: string;
  color?: string;
  strokeWidth?: number;
}

export function ObjectGlyph({
  icon,
  className = 'w-4 h-4',
  color,
  strokeWidth = 1.9,
}: ObjectGlyphProps) {
  const Icon = OBJECT_ICON_COMPONENTS[icon] ?? MapPin;
  return (
    <Icon
      className={className}
      style={color ? { color } : undefined}
      strokeWidth={strokeWidth}
      aria-hidden="true"
    />
  );
}
